"""Filtered Hilbert functions by direct computation in the edge algebra.

Standard library only; exact integer arithmetic.  Nothing from the paper is
used beyond the definitions:

    Phi_G = Q[phi_e : e in E] / (phi_e^2),   X_v = sum_e c(v,e) phi_e,
    Y_v = f(X_v),   F_d = span of all products of at most d of the Y_v,

and the Hilbert function h_d = dim F_d - dim F_{d-1}.  Elements of Phi_G are
dictionaries {bitmask of edges: coefficient}.  The polynomial f is given by
its coefficients {k: a_k} (no constant term).  Coefficients may be Fractions;
they are cleared to integers first, which does not change any span.

F_d = F_{d-1} + sum_v Y_v F_{d-1}, and Y_v F_{d-2} lies in F_{d-1}, so only the
basis vectors added at the previous step need to be multiplied (frontier).
Spans are kept in integer echelon form (fraction-free elimination with
primitive rows), so all ranks are exact ranks over Q.

The same code computes the subalgebra generated by f(X_v) when f has no
linear term; it then does not exhaust the zonotopal algebra.
"""
from fractions import Fraction
from math import gcd, factorial, lcm
from itertools import combinations


def integer_coefficients(f):
    f = {k: Fraction(a) for k, a in f.items() if a}
    den = 1
    for a in f.values():
        den = lcm(den, a.denominator)
    return {k: int(a * den) for k, a in f.items()}


def generators(n, edges, f):
    """Y_v = f(X_v) for v = 0..n-1; edge (u, w) is oriented from u to w; loops give zero."""
    f = integer_coefficients(f)
    gens = []
    for v in range(n):
        inc = []
        for i, (a, b) in enumerate(edges):
            if a == b:
                continue
            if v == a:
                inc.append((1 << i, -1))
            elif v == b:
                inc.append((1 << i, 1))
        y = {}
        for k, a in f.items():
            if k > len(inc):
                continue
            c = a * factorial(k)
            for sub in combinations(inc, k):
                mask, sign = 0, 1
                for bit, s in sub:
                    mask |= bit
                    sign *= s
                y[mask] = y.get(mask, 0) + c * sign
        gens.append({m: c for m, c in y.items() if c})
    return gens


def multiply(x, y):
    out = {}
    for i, a in x.items():
        for j, b in y.items():
            if not i & j:
                k = i | j
                out[k] = out.get(k, 0) + a * b
    return {k: c for k, c in out.items() if c}


def _primitive(v):
    g = 0
    for c in v.values():
        g = gcd(g, c)
        if g == 1:
            break
    if v[min(v)] < 0:
        g = -g
    return {k: c // g for k, c in v.items()}


class EchelonSpace:
    """Span of integer vectors; each stored row has a distinct leading (smallest) key."""

    def __init__(self):
        self.rows = {}

    def insert(self, v):
        """Reduce v; if it is new, store and return the reduced row, else return None."""
        v = dict(v)
        while v:
            p = min(v)
            row = self.rows.get(p)
            if row is None:
                v = _primitive(v)
                self.rows[p] = v
                return v
            a, b = row[p], v[p]
            g = gcd(a, b)
            a, b = a // g, b // g
            w = {k: a * c for k, c in v.items()}
            for k, c in row.items():
                d = w.get(k, 0) - b * c
                if d:
                    w[k] = d
                else:
                    w.pop(k, None)
            v = _primitive(w) if w else w
        return None

    def __len__(self):
        return len(self.rows)


def hilbert_direct(n, edges, f, gens=None):
    """Hilbert function [h_0, h_1, ...] of the filtration by products of the f(X_v)."""
    if gens is None:
        gens = generators(n, edges, f)
    gens = [g for g in gens if g]
    space = EchelonSpace()
    frontier = [space.insert({0: 1})]
    h = [1]
    while frontier:
        new = []
        for w in frontier:
            for g in gens:
                z = space.insert(multiply(w, g))
                if z is not None:
                    new.append(z)
        if new:
            h.append(len(new))
        frontier = new
    return h


def number_of_forests(n, edges):
    """Number of edge subsets without cycles (loops are cycles)."""
    count = 0
    m = len(edges)
    for mask in range(1 << m):
        parent = list(range(n))

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x
        ok = True
        for i in range(m):
            if mask >> i & 1:
                a, b = find(edges[i][0]), find(edges[i][1])
                if a == b:
                    ok = False
                    break
                parent[a] = b
        count += ok
    return count


