"""Exact checks of the collision pairs G8, T1, T2, T3 (Propositions 6.15, 6.16, Remark 6.17).

    python3 verify_pairs.py [--jobs 4]

For each pair (edge lists as in (6.16) of the paper, vertices numbered from 1)
this script
  1. confirms that the two graphs are not isomorphic (canonical forms);
  2. computes the filtered Hilbert functions directly in the edge algebra,
     by exact integer elimination, for the nondegenerate functions below,
     and for trees also by the boundary-state calculus, and checks that the
     two graphs of the pair agree;
  3. computes the Hilbert functions of the filtered subalgebras generated by
     f(X_v) for degenerate f (no linear term), as in [NSh, Problem 5], and
     reports whether the two graphs agree;
  4. computes the Hilbert series of the external bizonotopal algebras of
     Kirillov, Nenashev, Shapiro and Vaintrob (number of partial score
     vectors of each weight) and reports whether they agree.

Degenerate functions.  All four pairs have maximum degree at most three, so
X_v^4 = 0.  The automorphism phi_e -> lambda*phi_e of the edge algebra sends
f(X_v) to f(lambda X_v), so f(u) and f(lambda u) give the same Hilbert series,
and so do nonzero multiples of f.  Hence every f without linear term is,
modulo u^4, proportional to u^2, u^2+u^3 or u^3, or is zero.  The rows u^2,
u^2+u^3 and u^3 for T3 therefore show that T3_1 and T3_2 have the same
Hilbert series for every polynomial f (Proposition 6.16(i)); the row u^2
separates G8, T1 and T2 (Proposition 6.16(ii)).  The other degenerate
functions in the list are included as a consistency check of this reduction.
"""
import argparse
import os
from collections import Counter
from fractions import Fraction
from itertools import product
from multiprocessing import Pool

from small_graphs import tree_key, unicycle_key
from hilbert_direct import hilbert_direct
from hilbert_boundary import LocalRule, hilbert_tree

PAIRS = {
    'G8': ('12 23 34 41 15 56 27 38', '12 23 34 41 15 56 27 48'),
    'T1': ('12 23 34 45 56 27 48 29 8-10', '12 23 34 45 56 27 48 29 1-10'),
    'T2': ('12 23 34 45 56 27 38 89 9-10', '12 23 34 45 56 27 38 19 9-10'),
    'T3': ('12 13 14 25 26 37 38 49 9-10', '12 13 14 25 26 37 38 59 9-10'),
}

F = Fraction
NONDEGENERATE = {
    'u+u^2': {1: 1, 2: 1},
    'u+u^2+u^3': {1: 1, 2: 1, 3: 1},
    'u+u^2+2u^3': {1: 1, 2: 1, 3: 2},
    'u+u^3': {1: 1, 3: 1},
    'u+u^4': {1: 1, 4: 1},
    'u+u^3+u^4': {1: 1, 3: 1, 4: 1},
    'u+u^2+3u^3+10u^4': {1: 1, 2: 1, 3: 3, 4: 10},
    'u+u^2+2u^3+5u^4': {1: 1, 2: 1, 3: 2, 4: 5},
    'u+u^2+3u^3+7u^4': {1: 1, 2: 1, 3: 3, 4: 7},
    'exp jet': {1: 1, 2: F(1, 2), 3: F(1, 6), 4: F(1, 24)},
}
DEGENERATE = {
    'u^2': {2: 1},
    'u^2+u^3': {2: 1, 3: 1},
    'u^2+2u^3': {2: 1, 3: 2},
    'u^2+u^3+u^4': {2: 1, 3: 1, 4: 1},
    'u^2+u^4': {2: 1, 4: 1},
    'u^3': {3: 1},
    'u^3+u^4': {3: 1, 4: 1},
    'u^4': {4: 1},
}


def parse(s):
    edges = []
    for tok in s.split():
        a, b = tok.split('-') if '-' in tok else (tok[0], tok[1])
        edges.append((int(a) - 1, int(b) - 1))
    n = 1 + max(max(e) for e in edges)
    return n, edges


def partial_score_series(n, edges):
    """Hilbert series of the external bizonotopal algebra: partial score vectors by weight."""
    vectors = set()
    for choice in product((0, 1, 2), repeat=len(edges)):
        a = [0] * n
        for (u, v), c in zip(edges, choice):
            if c == 1:
                a[u] += 1
            elif c == 2:
                a[v] += 1
        vectors.add(tuple(a))
    weights = Counter(sum(a) for a in vectors)
    return [weights[k] for k in range(max(weights) + 1)]


def job(args):
    label, side, n, edges, name, f = args
    return label, side, name, hilbert_direct(n, edges, f)


def main(jobs):
    graphs = {(label, side): parse(s) for label, pair in PAIRS.items() for side, s in enumerate(pair)}
    lines = []
    for label in PAIRS:
        (n, e0), (_, e1) = graphs[label, 0], graphs[label, 1]
        key = tree_key if len(e0) == n - 1 else unicycle_key
        assert key(n, e0) != key(n, e1)
        lines.append(f'{label}: the two graphs are not isomorphic (canonical forms differ)')
    tasks = [(label, side, n, edges, name, f)
             for (label, side), (n, edges) in graphs.items()
             for name, f in list(NONDEGENERATE.items()) + list(DEGENERATE.items())]
    with Pool(jobs) as pool:
        results = {(label, side, name): h for label, side, name, h in pool.map(job, tasks, chunksize=1)}
    for label in PAIRS:
        lines.append('')
        lines.append(f'== {label}')
        n, e0 = graphs[label, 0]
        is_tree = len(e0) == n - 1
        for name, f in NONDEGENERATE.items():
            h0, h1 = results[label, 0, name], results[label, 1, name]
            assert h0 == h1, (label, name, h0, h1)
            if is_tree:
                R = LocalRule(f)
                for side in (0, 1):
                    assert hilbert_tree(n, graphs[label, side][1], R) == results[label, side, name]
            lines.append(f'  {name:18s} equal  {h0}' + ('  (direct = boundary)' if is_tree else '  (direct)'))
        for name in DEGENERATE:
            h0, h1 = results[label, 0, name], results[label, 1, name]
            tag = 'equal ' if h0 == h1 else 'DIFFER'
            lines.append(f'  {name:18s} {tag} {h0}' + ('' if h0 == h1 else f' vs {h1}'))
        b0, b1 = (partial_score_series(*graphs[label, side]) for side in (0, 1))
        tag = 'equal ' if b0 == b1 else 'DIFFER'
        lines.append(f'  {"bizonotopal B^e":18s} {tag} {b0}' + ('' if b0 == b1 else f' vs {b1}'))
    report = '\n'.join(lines)
    os.makedirs('results', exist_ok=True)
    with open('results/pairs.txt', 'w') as fh:
        fh.write(report + '\n')
    print(report)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--jobs', type=int, default=os.cpu_count() or 1)
    main(ap.parse_args().jobs)
