"""Fast modular evaluation of filtered Hilbert functions h(G, f) (numpy, standard library otherwise).

Setup as in the paper: Phi_G = K[phi_e]/(phi_e^2), X_v = sum_e c(v,e) phi_e, Y_v = f(X_v),
F_d = span of products of at most d of the Y_v, h_d = dim F_d - dim F_{d-1}.

All F_d lie in the subalgebra C_G generated by the X_v.  We compute a basis of C_G modulo p,
degree by degree, in reduced echelon form; a vector of C_G is then determined by its entries in
the pivot columns.  Multiplication by X_v is stored as a matrix in these coordinates, and
Y_v = f(X_v) is a matrix polynomial.  Ranks are exact ranks over GF(p).

p must be prime and below 2^20 (float64 matrix products are exact for dimensions < 8000).
"""
import itertools
import numpy as np

PBIG = 1048573  # largest prime below 2^20


def _mm(A, B, p):
    """Exact (A @ B) mod p for int64 matrices with entries in [0, p)."""
    if A.shape[1] == 0:
        return np.zeros((A.shape[0], B.shape[1]), dtype=np.int64)
    # float64 sums are exact below 2^53: every product is < (p-1)^2
    assert A.shape[1] * (p - 1) ** 2 < 2 ** 53, 'inner dimension too large for exact float64 sums'
    C = np.asarray(A, dtype=np.float64) @ np.asarray(B, dtype=np.float64)
    return np.mod(C, p).astype(np.int64)


def rref_rows(C, p):
    """Reduced row echelon form of C mod p; returns (rows, pivot columns)."""
    M = np.mod(C, p).astype(np.int64)
    nrows, ncols = M.shape
    R = np.zeros((min(nrows, ncols), ncols), dtype=np.int64)
    piv = []
    r = 0
    for i in range(nrows):
        row = M[i]
        nz = np.flatnonzero(row)
        if nz.size == 0:
            continue
        j = nz[0]
        inv = pow(int(row[j]), p - 2, p)
        row = (row * inv) % p
        if i + 1 < nrows:
            col = M[i + 1:, j]
            rr = np.flatnonzero(col)
            if rr.size:
                rr += i + 1
                M[rr] = (M[rr] - np.outer(M[rr, j], row)) % p
        if r:
            col = R[:r, j]
            rr = np.flatnonzero(col)
            if rr.size:
                R[rr] = (R[rr] - np.outer(R[rr, j], row)) % p
        R[r] = row
        r += 1
        piv.append(j)
    return R[:r].copy(), piv


class Space:
    """Subspace of GF(p)^D kept in reduced echelon form."""

    def __init__(self, D, p):
        self.D, self.p = D, p
        self.B = np.zeros((0, D), dtype=np.int64)
        self.piv = []

    def add(self, C):
        """Insert the rows of C; return a matrix whose rows span (span C + self)/self (in rref)."""
        p = self.p
        if len(self.piv):
            C = (C - _mm(C[:, self.piv], self.B, p)) % p
        N, npiv = rref_rows(C, p)
        if len(npiv):
            if len(self.piv):
                self.B = (self.B - _mm(self.B[:, npiv], N, p)) % p
            self.B = np.vstack([self.B, N])
            self.piv = self.piv + npiv
        return N

    def __len__(self):
        return len(self.piv)


def incidence(n, edges):
    inc = [[] for _ in range(n)]
    for i, (a, b) in enumerate(edges):
        if a == b:
            continue
        inc[a].append((i, -1))
        inc[b].append((i, 1))
    return inc


class GraphAlg:
    def __init__(self, n, edges, p=PBIG):
        self.n, self.edges, self.p = n, list(edges), p
        N = len(edges)
        self.N = N
        inc = incidence(n, edges)
        self.deg = [len(x) for x in inc]
        self.Delta = max(self.deg) if n else 0
        # full-space vectors as dicts mask -> coeff
        X = []
        for v in range(n):
            X.append({1 << i: s % p for i, s in inc[v]})
        self.Xfull = X
        # basis of C_G by ordinary degree, full vectors as dicts; coordinates = pivot columns
        basis = [{0: 1}]
        cols = [0]   # pivot column (mask) of each basis vector, in order
        prev = [{0: 1}]
        k = 0
        while prev:
            k += 1
            masks = sorted({m1 | m2 for b in prev for v in range(n) for m1 in b for m2 in X[v] if not m1 & m2})
            if not masks:
                break
            idx = {m: i for i, m in enumerate(masks)}
            rows = []
            for b in prev:
                for v in range(n):
                    vec = np.zeros(len(masks), dtype=np.int64)
                    for m1, c1 in b.items():
                        for m2, c2 in X[v].items():
                            if not m1 & m2:
                                j = idx[m1 | m2]
                                vec[j] = (vec[j] + c1 * c2) % p
                    rows.append(vec)
            R, piv = rref_rows(np.array(rows), p)
            new = []
            for r in R:
                nz = np.flatnonzero(r)
                new.append({masks[j]: int(r[j]) for j in nz})
            # pivot of row r is its first nonzero column = masks[piv]
            for r, j in zip(new, piv):
                basis.append(r)
                cols.append(masks[j])
            prev = new
        self.basis = basis
        self.cols = cols
        self.D = len(basis)
        colidx = {m: i for i, m in enumerate(cols)}
        # multiplication by X_v in coordinates (row-vector convention)
        self.MX = []
        for v in range(n):
            M = np.zeros((self.D, self.D), dtype=np.int64)
            for i, b in enumerate(basis):
                for m1, c1 in b.items():
                    for m2, c2 in X[v].items():
                        if not m1 & m2:
                            m = m1 | m2
                            j = colidx.get(m)
                            if j is not None:
                                M[i, j] = (M[i, j] + c1 * c2) % p
            self.MX.append(M)
        # powers of MX_v up to deg v
        self.MXpow = []
        for v in range(n):
            pw = [np.eye(self.D, dtype=np.int64)]
            for k in range(1, self.deg[v] + 1):
                pw.append(_mm(pw[-1], self.MX[v], p))
            self.MXpow.append(pw)

    def Ymats(self, coeffs):
        """coeffs: dict k -> a_k (ints or Fractions) of f(u) = sum a_k u^k."""
        p = self.p
        cf = {}
        for k, a in coeffs.items():
            if hasattr(a, 'denominator'):
                a = a.numerator * pow(a.denominator, p - 2, p)
            cf[k] = int(a) % p
        Ys = []
        for v in range(self.n):
            M = np.zeros((self.D, self.D), dtype=np.int64)
            for k, a in cf.items():
                if a and k <= self.deg[v]:
                    M = (M + a * self.MXpow[v][k]) % p
            if M.any():
                Ys.append(M)
        return Ys

    def hilbert(self, coeffs, Ys=None):
        p = self.p
        if Ys is None:
            Ys = self.Ymats(coeffs)
        S = Space(self.D, p)
        e0 = np.zeros((1, self.D), dtype=np.int64)
        e0[0, 0] = 1
        fr = S.add(e0)
        h = [1]
        while len(fr):
            C = np.vstack([_mm(fr, Y, p) for Y in Ys]) if Ys else np.zeros((0, self.D), dtype=np.int64)
            fr = S.add(C) if len(C) else C
            if len(fr):
                h.append(len(fr))
        return h


def number_of_forests(n, edges):
    count = 0
    m = len(edges)
    for mask in range(1 << m):
        parent = list(range(n))

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x
        ok = True
        for i in range(m):
            if mask >> i & 1:
                a, b = find(edges[i][0]), find(edges[i][1])
                if a == b:
                    ok = False
                    break
                parent[a] = b
        count += ok
    return count


def connected_graphs(nv):
    """Connected simple graphs on nv vertices up to isomorphism (brute-force canonical form)."""
    allE = list(itertools.combinations(range(nv), 2))
    seen = set()
    perms = list(itertools.permutations(range(nv)))
    out = []
    for m in range(nv - 1, len(allE) + 1):
        for E in itertools.combinations(allE, m):
            adj = {i: set() for i in range(nv)}
            for a, b in E:
                adj[a].add(b)
                adj[b].add(a)
            st, vis = [0], {0}
            while st:
                x = st.pop()
                for y in adj[x]:
                    if y not in vis:
                        vis.add(y)
                        st.append(y)
            if len(vis) < nv:
                continue
            key = min(tuple(sorted(tuple(sorted((q[a], q[b]))) for a, b in E)) for q in perms)
            if key in seen:
                continue
            seen.add(key)
            out.append(list(E))
    return out


def canon(nv, E):
    """Canonical form of a multigraph (sorted edge multiset minimized over vertex permutations)."""
    return min(tuple(sorted(tuple(sorted((q[a], q[b]))) for a, b in E)) for q in itertools.permutations(range(nv)))


